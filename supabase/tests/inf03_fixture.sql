      create table public.schedules (id bigserial primary key, name text);
      grant usage on sequence public.schedules_id_seq to authenticated;
    elsif name = 'classes' then
      create table public.classes (id bigint generated by default as identity primary key, name text);
    end if;
    if name in ('clubs','classes','schedules') then
      execute format('insert into public.%I (name) values (''Synthetic public content'')', name);
    end if;
    execute format('create policy broad_public_write on public.%I for all using (true) with check (true)', name);
    execute format('create policy another_broad_write on public.%I for update using (true) with check (true)', name);
  end loop;
  foreach name in array array['admin_profiles','registrations','clubs','classes','schedules','banners','page_content']
  loop
    execute format('alter table public.%I enable row level security', name);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', name);
